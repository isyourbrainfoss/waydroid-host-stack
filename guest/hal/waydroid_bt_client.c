/*
 * Minimal guest-side client for waydroid-bt-host IPC (protocol v1 framing).
 *
 * Sends Ping and prints protocol version. Used to validate LXC socket mount
 * before the full Bluetooth system service backend is wired.
 *
 * Build (host or guest with gcc):
 *   gcc -O2 -o waydroid_bt_client waydroid_bt_client.c
 *
 * Run inside Waydroid:
 *   waydroid_bt_client /dev/socket/waydroid_bt
 *
 * Note: This client does not link libprotobuf; it only checks that the socket
 * accepts a connection and that a length-prefixed response returns. For full
 * encode/decode use the Rust protocol crate or a generated protobuf stub.
 */

#include <errno.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <sys/socket.h>
#include <sys/un.h>
#include <unistd.h>

/* Hand-built Ping request matching waydroid_bt.v1.Envelope wire layout is
 * non-trivial without protobuf. We send a minimal invalid probe first for
 * connectivity, then document that full Ping needs generated stubs.
 *
 * Connectivity test: connect + send 4 zero length (empty frame) is invalid;
 * instead we only verify connect(2) succeeds unless WAYDROID_BT_SEND_PING=1
 * and a pre-encoded frame file is provided.
 */

static int connect_unix(const char *path) {
    int fd = socket(AF_UNIX, SOCK_STREAM, 0);
    if (fd < 0) {
        perror("socket");
        return -1;
    }
    struct sockaddr_un addr;
    memset(&addr, 0, sizeof(addr));
    addr.sun_family = AF_UNIX;
    if (strlen(path) >= sizeof(addr.sun_path)) {
        fprintf(stderr, "path too long: %s\n", path);
        close(fd);
        return -1;
    }
    strncpy(addr.sun_path, path, sizeof(addr.sun_path) - 1);
    if (connect(fd, (struct sockaddr *)&addr, sizeof(addr)) < 0) {
        perror("connect");
        close(fd);
        return -1;
    }
    return fd;
}

/* Pre-encoded Ping frame (request_id=1, client_name="guest-c") generated by
 * the Rust protocol tests / tools/encode_ping. Update if schema changes.
 * If unavailable, length 0 means skip send.
 */
static const unsigned char PING_FRAME[] = {
    /* Placeholder: real frame written by scripts/gen_ping_frame.sh after build */
};

int main(int argc, char **argv) {
    const char *path = "/dev/socket/waydroid_bt";
    if (argc > 1) {
        path = argv[1];
    }

    printf("waydroid_bt_client: connecting to %s\n", path);
    int fd = connect_unix(path);
    if (fd < 0) {
        fprintf(stderr, "FAIL: cannot connect (is waydroid-bt-host running? LXC mount set?)\n");
        return 1;
    }
    printf("OK: connected to host bridge\n");

    if (sizeof(PING_FRAME) > 0) {
        if (write(fd, PING_FRAME, sizeof(PING_FRAME)) != (ssize_t)sizeof(PING_FRAME)) {
            perror("write");
            close(fd);
            return 1;
        }
        uint32_t len = 0;
        if (read(fd, &len, 4) != 4) {
            perror("read len");
            close(fd);
            return 1;
        }
        printf("OK: response length = %u\n", len);
        if (len > 0 && len < 1024 * 1024) {
            unsigned char buf[4096];
            size_t got = 0;
            while (got < len && got < sizeof(buf)) {
                ssize_t n = read(fd, buf + got, (len < sizeof(buf) ? len : sizeof(buf)) - got);
                if (n <= 0) break;
                got += (size_t)n;
            }
            printf("OK: read %zu payload bytes\n", got);
        }
    } else {
        printf("NOTE: no embedded Ping frame; connectivity-only check passed\n");
        printf("      build scripts/gen_ping_frame and regenerate this client for full Ping\n");
    }

    close(fd);
    return 0;
}
